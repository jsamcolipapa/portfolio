// Writes src/app/data/contact.generated.ts from environment variables, so contact
// details never live in the repository. Runs before start, build and test.
// Values come from a local .env (gitignored) or, in CI, from repository variables.
import { existsSync, writeFileSync } from 'node:fs';

if (existsSync('.env')) {
  process.loadEnvFile('.env');
}

const read = (name) => process.env[name]?.trim() || null;

const fail = (message) => {
  console.error(`generate-contact: ${message}`);
  process.exit(1);
};

const readUrl = (name) => {
  const value = read(name);
  if (value && !value.startsWith('https://')) {
    fail(`${name} must start with https://`);
  }
  return value;
};

const email = read('CONTACT_EMAIL');
if (email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
  fail('CONTACT_EMAIL is not a valid email address');
}

// The address is stored reversed and base64-encoded so it is not readable as plain
// text in the deployed bundle. It is decoded in the browser when a visitor asks for it.
const encodedEmail = email ? Buffer.from([...email].reverse().join('')).toString('base64') : null;

const values = {
  email: encodedEmail,
  linkedin: readUrl('CONTACT_LINKEDIN_URL'),
  github: readUrl('CONTACT_GITHUB_URL'),
};

const lines = Object.entries(values).map(
  ([key, value]) => `  ${key}: ${value === null ? 'null' : `'${value.replaceAll("'", "\\'")}'`},`,
);

writeFileSync(
  'src/app/data/contact.generated.ts',
  `// Generated by scripts/generate-contact.mjs. Do not edit or commit.
export const CONTACT_VALUES: Record<'email' | 'linkedin' | 'github', string | null> = {
${lines.join('\n')}
};
`,
);
